	@DeleteMapping("/deleteAutoGenerate/{id}")
	public ResponseEntity<?> delete(
	        @PathVariable Long id){

	    Optional<ProductionPlanningAutoGenerateMixingMillAndProduction> data =
	            planningAutoGenerateMixingMillAndProductionRepository.findById(id);


	    if(data.isEmpty()){
	        return ResponseEntity.badRequest()
	                .body("Data not found");
	    }


	    ProductionPlanningAutoGenerateMixingMillAndProduction row =
	            data.get();


	    planningAutoGenerateMixingMillAndProductionRepository
	            .deleteByPlanIdAndChangeoverIdAndCompoundCodeAndMouldNameAndType(
	                    row.getPlanId(),
	                    row.getChangeoverId(),
	                    row.getCompoundCode(),
	                    row.getMouldName(),
	                    row.getType()
	            );


	    return ResponseEntity.ok("All Shift Deleted");

	}
	
