	@PostMapping("/insertProductionPlanningChangeOverPlan")
	public ResponseEntity<Object> insertProductionPlanningChangeOverPlan(
	        @RequestBody ProductionPlanningChangeoverPlan jsonObject) {

	    try {

	        System.out.println("===== REQUEST RECEIVED =====");
	        System.out.println("MOULD     : " + jsonObject.getMouldName());
	        System.out.println("MACHINE   : " + jsonObject.getMachineName());
	        System.out.println("ARTICLE   : " + jsonObject.getArticle());
	        System.out.println("PLAN TYPE : " + jsonObject.getPlanType());

	        Optional<ProductionMouldMaster> mouldOptional =
	        		productionMouldRepository.findByMould(jsonObject.getMouldName());

	        System.out.println("MOULD FOUND: " + mouldOptional.isPresent());

	        if (!mouldOptional.isPresent()) {
	            System.out.println("❌ MOULD NOT FOUND IN DB");
	            return new ResponseEntity<>("Mould not found.", HttpStatus.NOT_ACCEPTABLE);
	        }

	        // 🔥 STEP 3 - MACHINE CHECK
	        Optional<MachineMaster> machineOptional =
	                machineMasterRepositoryObject.findByMachineName(jsonObject.getMachineName());

	        System.out.println("MACHINE FOUND: " + machineOptional.isPresent());

	        if (!machineOptional.isPresent()) {
	            System.out.println("❌ MACHINE NOT FOUND IN DB");
	            return new ResponseEntity<>("Machine not found.", HttpStatus.NOT_ACCEPTABLE);
	        }

	        Optional<ProductionArticleMaster> articleOptional =
	        		productionArticleMasterRepository.findByArticle(jsonObject.getArticle());

	        System.out.println("ARTICLE FOUND: " + articleOptional.isPresent());

	        if (!articleOptional.isPresent()) {
	            System.out.println("❌ ARTICLE NOT FOUND IN DB");
	            return new ResponseEntity<>("Article not found.", HttpStatus.NOT_ACCEPTABLE);
	        }

	        Optional<ProductionPlanningChangeoverPlan> productionOptional =
	                productionPlanningChangeoverPlanRepositoryObject
	                        .findTopByMachineNameOrderBySequenceNoDesc(jsonObject.getMachineName());

	        if (productionOptional.isPresent()) {
	            jsonObject.setSequenceNo(productionOptional.get().getSequenceNo() + 1);
	        } else {
	            jsonObject.setSequenceNo(1L);
	        }

	        // 🔥 STEP 6 - FINAL SAVE
	        jsonObject.setStatus("Pending");
	        jsonObject.setPendingShots(0L);
	        jsonObject.setAutoGeneratedSaved(0);
	        jsonObject.setDateTimeCreation(dateTimeService.getCurrentDateAndTime());
	        jsonObject.setDateTimeModified(dateTimeService.getCurrentDateAndTime());

	        productionPlanningChangeoverPlanRepositoryObject.save(jsonObject);

	        System.out.println("✅ SUCCESSFULLY SAVED");

	        return new ResponseEntity<>("Data added successfully.", HttpStatus.OK);

	    } catch (Exception e) {
	        System.out.println("🔥 EXCEPTION OCCURRED");
	        e.printStackTrace();
	        return new ResponseEntity<>("Something went wrong.", HttpStatus.INTERNAL_SERVER_ERROR);
	    }
	}

