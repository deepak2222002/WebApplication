	@GetMapping("/checkMouldAvailability")
	public ResponseEntity<?> checkMouldAvailability(
	        @RequestParam String mould,
	        @RequestParam String article,
	        @RequestParam String plannedDate,
	        @RequestParam String machineName
	) {

	    Integer minShots = productionPlanningChangeoverPlanRepositoryObject.getMinShotsByMould(mould);
	    if (minShots == null) minShots = 0;

	    Integer usedShots = productionPlanningChangeoverPlanRepositoryObject.getUsedShotsByMouldAndDate(mould, plannedDate);
	    if (usedShots == null) usedShots = 0;

	    int remainingShots = minShots - usedShots;
	    if (remainingShots < 0) remainingShots = 0;

	    // ✅ check mould already running on other machine (including duplicate)
	    String usedInMachine =
	            productionPlanningChangeoverPlanRepositoryObject.findOtherMachineUsingMouldOrDuplicate(
	                    mould, plannedDate, machineName
	            );

	    boolean isAlreadyUsed = usedInMachine != null;

	    MouldAvailabilityResponse response = new MouldAvailabilityResponse(
	            minShots,
	            usedShots,
	            remainingShots,
	            isAlreadyUsed,
	   
	            usedInMachine
	    );

	    return ResponseEntity.ok(response);
	}
	
	
	private String generatePlanId() {

	    return  LocalDateTime.now()
	            .format(DateTimeFormatter.ofPattern("yyyyMMddHHmmss"))
	            + "-"
	            + UUID.randomUUID()
	            .toString()
	            .substring(0, 8);

	}
	

	
	@PostMapping("/saveAutoGeneratedPlan")
	public ResponseEntity<?> saveAutoGeneratedPlan(
	        @RequestBody AutoGeneratedPlanDTO dto) {

	    // One Plan ID for complete upload
	    String commonPlanId = generatePlanId();

	    dto.getMachinePlans().forEach(machine -> {

	        savePlanData(
	                machine.getMachineName(),
	                machine.getMainChangeoverId(),
	                commonPlanId,
	                dto
	        );

	        savePlanData(
	                machine.getMachineName(),
	                machine.getNextChangeoverId(),
	                commonPlanId,
	                dto
	        );

	        savePlanData(
	                machine.getMachineName(),
	                machine.getSpareChangeoverId(),
	                commonPlanId,
	                dto
	        );
	    });

	    return ResponseEntity.ok("Saved Successfully");
	}

