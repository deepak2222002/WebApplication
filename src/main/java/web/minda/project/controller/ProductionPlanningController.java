	@PutMapping("/updateProductionPlanningChangeOverPlan")
	public ResponseEntity<?> updateProductionPlanningChangeOverPlan(
	        @RequestBody ProductionPlanningChangeoverPlan dto) {

	    ProductionPlanningChangeoverPlan plan =
	    		productionPlanningChangeoverPlanRepositoryObject.findById(dto.getChangeoverId())
	        .orElseThrow(() -> new RuntimeException("Invalid ID"));

	    plan.setArticle(dto.getArticle());
	    plan.setMouldName(dto.getMouldName());
	    plan.setDuplicateMouldName(dto.getDuplicateMouldName());
	    plan.setBatchCode(dto.getBatchCode());
	    plan.setPlannedShots(dto.getPlannedShots());
	    plan.setPriority(dto.getPriority());
	    plan.setPlannedDate(dto.getPlannedDate());
	    
	    plan.setPlannedDate(dateTimeService.getCurrentDateAndTime());
	
	    productionPlanningChangeoverPlanRepositoryObject.save(plan);

	    return ResponseEntity.ok("Updated Successfully");
	}
	
	
	

	
	@Transactional
	@DeleteMapping("/deletePlan/{machineName}/{plannedDate}/{planType}")
	public ResponseEntity<?> deletePlan(
	        @PathVariable String machineName,
	        @PathVariable String plannedDate,
	        @PathVariable String planType) {

	    if (planType.equalsIgnoreCase("all")) {
	    	productionPlanningRepositoryObject
	            .deleteByMachineNameAndPlannedDate(machineName, plannedDate);

	        return ResponseEntity.ok("All plans deleted for date " + plannedDate);
	    }

	    productionPlanningRepositoryObject
	        .deleteByMachineNameAndPlannedDateAndPlanType(machineName, plannedDate, planType);

	    return ResponseEntity.ok(planType + " deleted for date " + plannedDate);
	}
	
	
